//! The TypeScript declarations of the API's DTOs, for the panel: `web/src/api/generated.ts`.
//!
//! `cargo test -p brume-api export_typescript_bindings` writes the file. With
//! `BRUME_CHECK_BINDINGS=1`, it fails instead if the file differs. `BRUME_BINDINGS_OUT=<path>`
//! targets another file.

use std::path::PathBuf;

use brume_proto::api::{
    ActivityEventDto, ChangesDeployedDto, CommitDto, CreatedProjectDto, DatabaseKindDto,
    DeploymentDto, DeploymentStatusDto, EnvironmentDto, EventsPageDto, ImpactedServiceDto,
    LogLevel, LogLineDto, LogStream, NewChangeDto, NewProjectSourceDto, NewSharedVariableDto,
    ProjectDto, RevealedValueDto, RevisionDto, RevisionVariableDto, ServiceDto, ServiceKindDto,
    ServiceSettingsDto, ServiceSourceDto, ServiceStatusDto, SessionDto, SettingField,
    SettingValueDto, SharedVariableRemovedDto, SharedVariableSetDto, StagedChangeDto, VariableDto,
    VariableImpactDto, VariableKindDto, VariableLevelDto, VolumeDto,
};
use ts_rs::{Config, TS};

const HEADER: &str =
    "// Generated by cargo test -p brume-api export_typescript_bindings. Do not edit.\n";

/// The branded identifiers of `web/src/api/ids.ts`.
const IDS: [&str; 6] = [
    "ChangeId",
    "DeploymentId",
    "EnvironmentId",
    "ProjectId",
    "ServiceId",
    "VariableId",
];

/// The name and declaration of each DTO.
fn declarations() -> Vec<(String, String)> {
    fn entry<T: TS>(cfg: &Config) -> (String, String) {
        (T::name(cfg), T::decl(cfg))
    }
    let cfg = Config::default();
    vec![
        entry::<ActivityEventDto>(&cfg),
        entry::<ChangesDeployedDto>(&cfg),
        entry::<CommitDto>(&cfg),
        entry::<CreatedProjectDto>(&cfg),
        entry::<DatabaseKindDto>(&cfg),
        entry::<DeploymentDto>(&cfg),
        entry::<DeploymentStatusDto>(&cfg),
        entry::<EnvironmentDto>(&cfg),
        entry::<EventsPageDto>(&cfg),
        entry::<ImpactedServiceDto>(&cfg),
        entry::<LogLevel>(&cfg),
        entry::<LogLineDto>(&cfg),
        entry::<LogStream>(&cfg),
        entry::<NewChangeDto>(&cfg),
        entry::<NewProjectSourceDto>(&cfg),
        entry::<NewSharedVariableDto>(&cfg),
        entry::<ProjectDto>(&cfg),
        entry::<RevealedValueDto>(&cfg),
        entry::<RevisionDto>(&cfg),
        entry::<RevisionVariableDto>(&cfg),
        entry::<ServiceDto>(&cfg),
        entry::<ServiceKindDto>(&cfg),
        entry::<ServiceSettingsDto>(&cfg),
        entry::<ServiceSourceDto>(&cfg),
        entry::<ServiceStatusDto>(&cfg),
        entry::<SessionDto>(&cfg),
        entry::<SettingField>(&cfg),
        entry::<SettingValueDto>(&cfg),
        entry::<SharedVariableRemovedDto>(&cfg),
        entry::<SharedVariableSetDto>(&cfg),
        entry::<StagedChangeDto>(&cfg),
        entry::<VariableDto>(&cfg),
        entry::<VariableImpactDto>(&cfg),
        entry::<VariableKindDto>(&cfg),
        entry::<VariableLevelDto>(&cfg),
        entry::<VolumeDto>(&cfg),
    ]
}

/// The contents of `generated.ts`: the header, the import of the identifiers the declarations
/// use, then each declaration, exported, in alphabetical order of names. Arrays are read-only,
/// like everything the panel holds: it never mutates an answer.
pub(crate) fn bindings() -> String {
    let mut declarations = declarations();
    declarations.sort();
    let used: Vec<&str> = IDS
        .into_iter()
        .filter(|id| declarations.iter().any(|(_, decl)| mentions(decl, id)))
        .collect();
    let mut out = String::from(HEADER);
    out.push('\n');
    if !used.is_empty() {
        out.push_str(&format!(
            "import type {{ {} }} from \"./ids\";\n\n",
            used.join(", ")
        ));
    }
    for (_, decl) in &declarations {
        out.push_str("export ");
        out.push_str(&readonly_arrays(decl.trim_end()));
        out.push('\n');
    }
    out
}

/// `decl` with each `Array<…>` turned into a `ReadonlyArray<…>`.
fn readonly_arrays(decl: &str) -> String {
    let mut out = String::with_capacity(decl.len());
    let mut rest = decl;
    while let Some(at) = rest.find("Array<") {
        let (before, after) = rest.split_at(at);
        out.push_str(before);
        let whole_word = !before
            .chars()
            .next_back()
            .is_some_and(|c| c.is_ascii_alphanumeric() || c == '_');
        if whole_word {
            out.push_str("Readonly");
        }
        out.push_str("Array<");
        rest = &after["Array<".len()..];
    }
    out.push_str(rest);
    out
}

/// Whether `decl` uses the identifier `word` as a whole word.
fn mentions(decl: &str, word: &str) -> bool {
    decl.split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .any(|token| token == word)
}

/// `web/src/api/generated.ts`, or `BRUME_BINDINGS_OUT`.
fn output_path() -> PathBuf {
    match std::env::var_os("BRUME_BINDINGS_OUT") {
        Some(path) => PathBuf::from(path),
        None => PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../web/src/api/generated.ts"),
    }
}

#[test]
fn export_typescript_bindings() {
    let path = output_path();
    let bindings = bindings();
    if std::env::var_os("BRUME_CHECK_BINDINGS").is_some_and(|value| value == "1") {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            current == bindings,
            "{} is out of date: run cargo test -p brume-api export_typescript_bindings",
            path.display()
        );
    } else {
        std::fs::write(&path, bindings)
            .unwrap_or_else(|error| panic!("cannot write {}: {error}", path.display()));
    }
}

#[test]
fn bindings_declare_each_dto_once_in_order() {
    let bindings = bindings();
    assert!(bindings.starts_with(HEADER));
    assert!(bindings.contains(
        "import type { ChangeId, DeploymentId, EnvironmentId, ProjectId, ServiceId, \
         VariableId } from \"./ids\";"
    ));
    let names: Vec<&str> = bindings
        .lines()
        .filter_map(|line| line.strip_prefix("export type "))
        .filter_map(|rest| rest.split_once(' ').map(|(name, _)| name))
        .collect();
    let mut sorted = names.clone();
    sorted.sort_unstable();
    sorted.dedup();
    assert_eq!(names, sorted);
    // Every DTO that derives `TS` in brume-proto is declared.
    let derives = include_str!("../../brume-proto/src/api.rs")
        .matches("derive(ts_rs::TS)")
        .count();
    assert_eq!(names.len(), derives);
    for name in [
        "Project",
        "LogLine",
        "StagedChange",
        "ActivityPage",
        "DeploymentLogStream",
    ] {
        assert!(names.contains(&name), "{name}");
    }
    assert!(bindings.contains("environmentId: EnvironmentId"));
}

#[test]
fn arrays_are_read_only() {
    assert_eq!(
        readonly_arrays("{ a: Array<Array<string>>, b: ReadonlyArray<X>, c: MyArray<Y> }"),
        "{ a: ReadonlyArray<ReadonlyArray<string>>, b: ReadonlyArray<X>, c: MyArray<Y> }"
    );
    let bindings = bindings();
    assert!(bindings.contains("dependencies: ReadonlyArray<ServiceId>"));
    assert!(
        bindings
            .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
            .all(|token| token != "Array"),
        "{bindings}"
    );
}

#[test]
fn check_mode_fails_on_a_stale_file() {
    let dir = tempfile::tempdir().expect("creates a temporary directory");
    let path = dir.path().join("generated.ts");
    std::fs::write(&path, "stale").expect("writes");
    let output = std::process::Command::new(std::env::current_exe().expect("test binary"))
        .args(["--exact", "dto_ts::export_typescript_bindings"])
        .env("BRUME_BINDINGS_OUT", &path)
        .env("BRUME_CHECK_BINDINGS", "1")
        .output()
        .expect("runs the test binary");
    assert!(!output.status.success());
    assert_eq!(std::fs::read_to_string(&path).expect("reads"), "stale");

    let output = std::process::Command::new(std::env::current_exe().expect("test binary"))
        .args(["--exact", "dto_ts::export_typescript_bindings"])
        .env("BRUME_BINDINGS_OUT", &path)
        .env_remove("BRUME_CHECK_BINDINGS")
        .output()
        .expect("runs the test binary");
    assert!(output.status.success());
    assert_eq!(std::fs::read_to_string(&path).expect("reads"), bindings());
}
